import { readFileSync } from "node:fs";
import { afterAll, beforeAll, expect, it } from "vitest";
import { testDatabase, type TestDatabase } from "./support/database.js";
import { readRelations, RELATION_INVENTORY_PATH } from "../scripts/b1/relation-inventory.js";
import { FUNCTION_INVENTORY_PATH, readFunctionInventory, renderFunctionInventory } from "../scripts/b1/function-inventory.js";
import { strictJson } from "../services/kernel/src/database/strict-json.js";
import { engineVerifier, readPins } from "../scripts/b1/verify-engine-image.js";
import { DATABASE } from "./support/local.js";

/**
 * Lane A (base-regression): the committed relation inventory equals the base chain's catalogue. The declared refusals
 * of the relation probes in tests/b1-required.json are derived from it, so drift here fails before any stage T run.
 */
let database: TestDatabase;
beforeAll(async () => { database = await testDatabase("kj_relation_inventory"); });
afterAll(async () => { await database?.close(); });
it("the committed relation inventory equals the base chain's relations in public and kernel_private", async () => {
  expect(await readRelations(database.pool)).toEqual(strictJson(readFileSync(RELATION_INVENTORY_PATH, "utf8")));
});
/**
 * KJ-P8 B1 E2 (draft A10.7, not sealed): the committed function inventory is regenerated here, byte for byte, from the
 * base chain's catalogue with the shared predicate and identity expression, "C" ordering and an empty search_path
 * (scripts/b1/function-inventory.ts). B1 creates no function (CON-32); the post-B1 set is asserted equal in stage T by
 * the negative test. G8 derives its expected "function outside manifest" rows from this file at R.
 */
it("the committed function inventory is regenerated byte for byte from the base chain's catalogue", async () => {
  expect(renderFunctionInventory(await readFunctionInventory(database.pool))).toBe(readFileSync(FUNCTION_INVENTORY_PATH, "utf8"));
});
/**
 * KJ-P8 B1 A10.7 v7 (local candidate, not sealed) 2-R4/2-R4c, real: the lane A container runs the pinned digest and
 * serverVersion, DATABASE addresses that container's published binding, and the connection this file uses reports
 * the server identity recorded inside that container ID. A connection claimed for another port is refused (D12).
 */
it("the lane A database is the pinned engine image, and this file's connection is bound to the verified container", async () => {
  const pins = readPins(), verifier = engineVerifier(), v = verifier.verifyContainer(), url = new URL(DATABASE);
  expect(v.digest).toBe(pins.image);
  expect(v.identity.version).toBe(pins.serverVersion);
  expect(`${url.hostname}:${url.port}`).toBe(v.binding);
  const client = await database.pool.connect();
  try {
    await expect(verifier.verifyConnection(client, { host: v.host, port: v.port }, "tests/b1-relation-inventory.integration.test.ts")).resolves.toMatchObject({ containerId: v.containerId });
    await expect(verifier.verifyConnection(client, { host: v.host, port: v.port + 1 }, "tests/b1-relation-inventory.integration.test.ts")).rejects.toThrow(/ENGINE_IMAGE_REFUSED: url/);
  } finally { client.release(); }
});
/** 1-R10b: COLLATE "C" on the pinned engine orders exactly as the Buffer.compare UTF-8 comparator; nothing is created. */
it('VALUES ... ORDER BY x COLLATE "C" equals the Buffer.compare UTF-8 order (U+FF5E, U+1F600 and an ASCII control pair)', async () => {
  const literals = ["kj_\u{1F600}", "kj_\uFF5E", "kj_B", "kj_a", "kj_\u00E9", "kj__"];
  const values = literals.map((x) => `('${x.replaceAll("'", "''")}')`).join(", ");
  const rows = (await database.pool.query<{ x: string }>(`select x from (values ${values}) v(x) order by x collate "C"`)).rows.map((r) => r.x);
  const bytes = [...literals].sort((a, b) => Buffer.compare(Buffer.from(a, "utf8"), Buffer.from(b, "utf8")));
  expect(rows).toEqual(bytes);
  expect(bytes.indexOf("kj_\uFF5E")).toBeLessThan(bytes.indexOf("kj_\u{1F600}"));
  expect([...literals].sort().indexOf("kj_\u{1F600}")).toBeLessThan([...literals].sort().indexOf("kj_\uFF5E"));
});
