import { readFileSync } from "node:fs";
import { afterAll, beforeAll, expect, it } from "vitest";
import { testDatabase, type TestDatabase } from "./support/database.js";
import { readRelations, RELATION_INVENTORY_PATH } from "../scripts/b1/relation-inventory.js";
import { FUNCTION_INVENTORY_PATH, readFunctionInventory, renderFunctionInventory } from "../scripts/b1/function-inventory.js";
import { strictJson } from "../services/kernel/src/database/strict-json.js";

/**
 * Lane A (base-regression): the committed relation inventory equals the base chain's catalogue. The declared refusals
 * of the relation probes in tests/b1-required.json are derived from it, so drift here fails before any stage T run.
 */
let database: TestDatabase;
beforeAll(async () => { database = await testDatabase("kj_relation_inventory"); });
afterAll(async () => { await database?.close(); });
it("the committed relation inventory equals the base chain's relations in public and kernel_private", async () => {
  expect(await readRelations(database.pool)).toEqual(strictJson(readFileSync(RELATION_INVENTORY_PATH, "utf8")));
});
/**
 * KJ-P8 B1 E2 (draft A10.7, not sealed): the committed function inventory is regenerated here, byte for byte, from the
 * base chain's catalogue with the shared predicate and identity expression, "C" ordering and an empty search_path
 * (scripts/b1/function-inventory.ts). B1 creates no function (CON-32); the post-B1 set is asserted equal in stage T by
 * the negative test. G8 derives its expected "function outside manifest" rows from this file at R.
 */
it("the committed function inventory is regenerated byte for byte from the base chain's catalogue", async () => {
  expect(renderFunctionInventory(await readFunctionInventory(database.pool))).toBe(readFileSync(FUNCTION_INVENTORY_PATH, "utf8"));
});
